//! The JSON schema of `papyrus.toml`, for TOML editors: completion and
//! validation of its keys, the lints' included.

use papyrus_dialect::GameId;
use papyrus_lint::LINTS;
use serde_json::{Map, Value, json};

/// Where the schema is committed, from the workspace root.
pub(crate) const PATH: &str = "schemas/papyrus.schema.json";

fn path_value(description: &str) -> Value {
    json!({ "type": "string", "description": description })
}

/// The schema, as committed.
pub(crate) fn schema() -> String {
    let games: Vec<&str> = [
        GameId::Skyrim,
        GameId::Fallout4,
        GameId::Fallout76,
        GameId::Starfield,
    ]
    .iter()
    .map(|g| g.as_str())
    .chain([
        "sse", "skyrimse", "skyrimle", "skyrimae", "tesv", "fo4", "fo76", "sf",
    ])
    .collect();

    let level = json!({
        "type": "string",
        "enum": ["allow", "warn", "error", "off", "warning", "deny"],
        "enumDescriptions": [
            "Disabled.",
            "Reported as a warning.",
            "Reported as an error.",
            "Same as allow.",
            "Same as warn.",
            "Same as error.",
        ],
    });
    let mut lints = Map::new();
    for lint in LINTS {
        let description = format!(
            "{} ({}, {} by default)",
            lint.description,
            lint.code,
            lint.default.as_str()
        );
        let mut property = level.clone();
        property["description"] = json!(description);
        lints.insert(lint.name.to_owned(), property.clone());
        lints.insert(lint.code.to_owned(), property);
    }

    let schema = json!({
        "$schema": "http://json-schema.org/draft-07/schema#",
        "$id": papyrus_project::edit::SCHEMA_URL,
        "title": "papyrus.toml",
        "description": "The configuration of a Papyrus project, for the papyrus toolchain.",
        "type": "object",
        "additionalProperties": false,
        "properties": {
            "game": {
                "type": "string",
                "enum": games,
                "description": "The target game. Without it, it is inferred from the scripts.",
            },
            "include-fragments": {
                "type": "boolean",
                "default": false,
                "description": "Check the fragments generated by the Creation Kit too.",
            },
            "skse": {
                "type": "boolean",
                "default": false,
                "description": "Skyrim with SKSE installed: its functions and scripts are known.",
            },
            "flags": path_value("A .flg file replacing the game's vanilla flags, relative to this file."),
            "imports": {
                "type": "array",
                "items": { "type": "string" },
                "description": "Folders of scripts the project builds on — a library, another mod, the game's sources — read but never checked, relative to this file.",
            },
            "fmt": {
                "type": "object",
                "additionalProperties": false,
                "description": "The formatter.",
                "properties": {
                    "indent": {
                        "description": "1 to 8 spaces, or \"tab\". 2 spaces by default.",
                        "oneOf": [
                            { "type": "integer", "minimum": 1, "maximum": 8 },
                            { "type": "string", "enum": ["tab"] },
                        ],
                    },
                },
            },
            "lints": {
                "type": "object",
                "additionalProperties": false,
                "description": "The level of each lint, by name or by code.",
                "properties": lints,
            },
            "build": {
                "type": "object",
                "additionalProperties": false,
                "description": "How `papyrus build` compiles.",
                "properties": {
                    "compiler": path_value("PapyrusCompiler.exe, or Caprica. By default, the Creation Kit's of a default Steam installation."),
                    "output": path_value("Where the .pex files go, relative to this file. Scripts by default."),
                    "optimize": { "type": "boolean", "default": false, "description": "Optimize the bytecode." },
                    "release": { "type": "boolean", "default": false, "description": "Strip DebugOnly code (Fallout 4 onwards)." },
                    "final": { "type": "boolean", "default": false, "description": "Strip BetaOnly code (Fallout 4 onwards)." },
                },
            },
        },
    });
    let mut text = serde_json::to_string_pretty(&schema).expect("a JSON value");
    text.push('\n');
    text
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    #[test]
    fn the_schema_is_up_to_date() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("..")
            .join(super::PATH);
        let committed = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(
            committed.replace("\r\n", "\n") == super::schema(),
            "{} is out of date: run `cargo xtask schema`",
            super::PATH
        );
    }
}
