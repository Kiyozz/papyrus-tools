#[derive(Debug, Parser)]
#[command(
    name = "papyrus",
    version,
    about = "Check, format and build Papyrus scripts"
)]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Debug, Subcommand)]
enum Command {
    /// Report syntax errors and lint findings.
    Check(CheckArgs),
    /// Format scripts in place.
    Fmt(FmtArgs),
    /// Compile scripts with the Creation Kit's compiler or Caprica, and
    /// report their errors.
    Build(BuildArgs),
    /// Create a papyrus.toml for the scripts of a folder.
    Init(InitArgs),
    /// List the lints, their code and default level.
    Lints,
    /// Say what a lint means and what to do about it, by code or by name;
    /// `baseline` explains baselines.
    Explain {
        /// `PAP015`, `locals/unused` or `baseline`.
        lint: String,
    },
    /// Print a compiled script (.pex) as assembly, in the format of
    /// PapyrusAssembler.
    Disassemble {
        /// The `.pex` file.
        file: PathBuf,
    },
    /// Run the language server on standard input and output, for an
    /// editor.
    Lsp,
}

#[derive(Debug, Args)]
struct Common {
    /// Files or folders to process. Defaults to the current folder.
    paths: Vec<PathBuf>,

    /// Target game: skyrim, fallout4, fallout76, starfield (or sse, fo4, sf…).
    /// Overrides `game` in papyrus.toml.
    ///
    /// Without a target, the widest syntax is accepted, and encoding checks
    /// are skipped: their advice depends on the game.
    #[arg(long, short)]
    game: Option<GameId>,

    /// Include the fragments generated by the Creation Kit.
    #[arg(long)]
    include_fragments: bool,
}

#[derive(Debug, Args)]
struct CheckArgs {
    #[command(flatten)]
    common: Common,

    /// Apply safe fixes in place.
    #[arg(long)]
    fix: bool,

    /// With `--fix`, also apply unsafe fixes: the case of properties, which
    /// plugins (.esp, .esm) bind by name.
    #[arg(long = "unsafe", requires = "fix")]
    unsafe_fixes: bool,

    /// How problems are printed.
    #[arg(long, value_enum, default_value_t)]
    message_format: MessageFormat,

    /// Record today's problems in papyrus-baseline.json: `check` then only
    /// reports new ones. `papyrus explain baseline` says more.
    #[arg(long, conflicts_with = "no_baseline")]
    write_baseline: bool,

    /// Report the problems of papyrus-baseline.json too.
    #[arg(long)]
    no_baseline: bool,

    /// Check the script on standard input, rather than files.
    #[arg(long, conflicts_with_all = ["paths", "fix", "write_baseline"])]
    stdin: bool,

    /// With `--stdin`, where the script is: gives its project and its
    /// expected `ScriptName`.
    #[arg(long, requires = "stdin", value_name = "PATH")]
    stdin_filename: Option<PathBuf>,
}

#[derive(Debug, Args)]
struct FmtArgs {
    #[command(flatten)]
    common: Common,

    /// Write nothing; list the files to reformat and fail if there are any.
    #[arg(long)]
    check: bool,

    /// Format the script on standard input, on standard output.
    #[arg(long, conflicts_with = "paths")]
    stdin: bool,

    /// With `--stdin`, where the script is: gives its papyrus.toml.
    #[arg(long, requires = "stdin", value_name = "PATH")]
    stdin_filename: Option<PathBuf>,

    /// Indentation: a number of spaces, or `tab`. Two spaces by default, or
    /// `fmt.indent` from papyrus.toml.
    #[arg(long)]
    indent: Option<IndentArg>,
}

#[derive(Debug, Args)]
struct BuildArgs {
    #[command(flatten)]
    common: Common,

    /// The compiler: `PapyrusCompiler.exe`, or Caprica. Overrides
    /// `build.compiler` in papyrus.toml; without either, the Creation Kit's
    /// of a default Steam installation.
    #[arg(long)]
    compiler: Option<PathBuf>,

    /// Where the `.pex` files go. Overrides `build.output`; `Scripts` next
    /// to papyrus.toml by default.
    #[arg(long, short)]
    output: Option<PathBuf>,

    /// Optimize the bytecode.
    #[arg(long)]
    optimize: bool,

    /// Strip `DebugOnly` code (Fallout 4 onwards).
    #[arg(long)]
    release: bool,

    /// Strip `BetaOnly` code (Fallout 4 onwards).
    #[arg(long = "final")]
    final_: bool,

    /// How problems are printed.
    #[arg(long, value_enum, default_value_t)]
    message_format: MessageFormat,
}

#[derive(Debug, Args)]
struct InitArgs {
    /// The folder of the project. Defaults to the current folder.
    path: Option<PathBuf>,

    /// Target game. Inferred from the scripts by default.
    #[arg(long, short)]
    game: Option<GameId>,

    /// The Creation Kit or Pyro project to read, relative to the folder. By
    /// default, the only `.ppj` of the folder.
    #[arg(long)]
    ppj: Option<PathBuf>,
}

#[derive(Debug, Clone, Copy)]
struct IndentArg(Indent);

impl FromStr for IndentArg {
    type Err = String;

    fn from_str(s: &str) -> Result<IndentArg, String> {
        if s.eq_ignore_ascii_case("tab") || s.eq_ignore_ascii_case("tabs") {
            return Ok(IndentArg(Indent::Tabs));
        }
        match s.parse::<u8>() {
            Ok(n @ 1..=8) => Ok(IndentArg(Indent::Spaces(n))),
            _ => Err(format!(
                "`{s}`: expected a number of spaces from 1 to 8, or `tab`"
            )),
        }
    }
}

/// The settings of one project: command line, then its papyrus.toml, then
/// the defaults.
#[derive(Debug)]
struct Settings {
    /// The folder of its papyrus.toml, or the root it was found under.
    root: PathBuf,
    /// Its papyrus.toml.
    config: Config,
    scripts: Vec<PathBuf>,
    /// The scripts of the `imports` folders: read, never checked.
    imported: Vec<PathBuf>,
    game: Option<GameId>,
    indent: Indent,
    flags: Vec<FlagDef>,
    levels: Levels,
}

impl Settings {
    fn dialect(&self) -> Dialect {
        self.game.map(Dialect::new).unwrap_or_default()
    }

    /// The settings of every project under the given paths: each script
    /// follows the papyrus.toml that covers it.
    fn resolve(common: &Common, indent: Option<IndentArg>) -> Result<Vec<Settings>, String> {
        let roots = if common.paths.is_empty() {
            vec![PathBuf::from(".")]
        } else {
            common.paths.clone()
        };
        let projects = papyrus_project::projects(&roots, common.include_fragments)
            .map_err(|e| e.to_string())?;
        let several = projects.len() > 1;
        for project in &projects {
            for note in &project.config.notes {
                eprintln!("note: {}: {note}", project.root.display());
            }
        }
        projects
            .into_iter()
            .map(|project| Settings::of(project, common, indent, several))
            .collect()
    }

    fn of(
        project: Project,
        common: &Common,
        indent: Option<IndentArg>,
        several: bool,
    ) -> Result<Settings, String> {
        let config = &project.config;
        let in_config = |message: String| match &config.path {
            Some(path) => format!("{}: {message}", path.display()),
            None => message,
        };
        // With several projects, every message says which one it is about.
        let label = several.then(|| project.root.display().to_string());

        let game = common
            .game
            .or(config.game)
            .or_else(|| detect(&project.scripts, label.as_deref()));
        let flags = match &config.flags {
            Some(path) => {
                let text = std::fs::read_to_string(path)
                    .map_err(|e| format!("{}: {e}", path.display()))?;
                parse_flags(&text).map_err(|e| format!("{}: {e}", path.display()))?
            }
            None => vanilla_flags(game),
        };
        let levels = Levels::from_config(&config.lints).map_err(in_config)?;
        let indent = indent_of(indent, config);
        Ok(Settings {
            root: project.root,
            config: project.config,
            scripts: project.scripts,
            imported: project.imported,
            game,
            indent,
            flags,
            levels,
        })
    }

    /// The settings of the project `path` belongs to, even if it does not
    /// exist yet: a script from standard input.
    fn around(path: &Path, common: &Common) -> Result<Settings, String> {
        let config = Config::discover(path).map_err(|e| e.to_string())?;
        let root = ConfigLocator::default()
            .locate(path)
            .as_deref()
            .and_then(Path::parent)
            .or_else(|| path.parent())
            .unwrap_or(Path::new("."))
            .to_owned();
        let found = if root.is_dir() {
            papyrus_project::projects(std::slice::from_ref(&root), common.include_fragments)
                .map_err(|e| e.to_string())?
        } else {
            Vec::new()
        };
        let mut project = found
            .into_iter()
            .find(|p| p.root == root)
            .unwrap_or(Project {
                root,
                config,
                scripts: Vec::new(),
                imported: Vec::new(),
            });
        if !project.scripts.iter().any(|p| p == path) {
            project.scripts.push(path.to_owned());
        }
        Settings::of(project, common, None, false)
    }
}

/// The indentation: command line, then papyrus.toml, then the default.
fn indent_of(indent: Option<IndentArg>, config: &Config) -> Indent {
    match (indent, config.indent) {
        (Some(IndentArg(indent)), _) => indent,
        (None, Some(IndentSetting::Spaces(n))) => Indent::Spaces(n),
        (None, Some(IndentSetting::Tab)) => Indent::Tabs,
        (None, None) => Indent::default(),
    }
}

/// The formatter's case of keywords.
const fn keywords_of(config: &Config) -> KeywordCase {
    if config.pascal_keywords {
        KeywordCase::Pascal
    } else {
        KeywordCase::Lower
    }
}

/// Reads standard input.
fn read_stdin() -> Result<Vec<u8>, String> {
    let mut bytes = Vec::new();
    std::io::stdin()
        .read_to_end(&mut bytes)
        .map_err(|e| format!("standard input: {e}"))?;
    Ok(bytes)
}

/// Where the script on standard input is: where it was said to be, else
/// where its `ScriptName` puts it in the current folder.
fn stdin_path(given: Option<&Path>, text: &str) -> PathBuf {
    let path = given.map_or_else(
        || {
            let parse = papyrus_syntax::parse(text, Dialect::new(GameId::Starfield));
            let name = ScriptSummary::of(&parse.syntax()).map_or("stdin".to_owned(), |s| s.name);
            PathBuf::from(format!("{}.psc", name.replace(':', "/")))
        },
        Path::to_owned,
    );
    std::path::absolute(&path).unwrap_or(path)
}

/// Guesses the game of a project's scripts when neither `--game` nor its
/// papyrus.toml says it: the majority of the files that give it away.
///
/// Without any clue, `None`: the widest syntax applies, and game-dependent
/// lints stay quiet rather than guess.
fn detect(scripts: &[PathBuf], project: Option<&str>) -> Option<GameId> {
    let widest = Dialect::new(GameId::Starfield);
    let verdicts = scripts.iter().filter_map(|path| {
        let bytes = std::fs::read(path).ok()?;
        let parse = papyrus_syntax::parse(&decode(&bytes).text, widest);
        Some(papyrus_project::detect::evidence(&parse.syntax()).verdict())
    });
    let prefix = project.map(|p| format!("{p}: ")).unwrap_or_default();
    match papyrus_project::detect::majority(verdicts) {
        Some((game, votes, decided)) => {
            eprintln!(
                "{prefix}inferred target: {} ({votes} of {decided} file(s) point to it) — \
                 set `--game` or `game` in papyrus.toml to force it",
                game.display_name()
            );
            Some(game)
        }
        None => {
            eprintln!(
                "{prefix}unknown target: Starfield syntax, game-specific checks skipped — \
                 set `--game` or `game` in papyrus.toml"
            );
            None
        }
    }
}

fn main() -> ExitCode {
    let cli = Cli::parse();
    let mut reporter = Reporter::new(std::io::stderr().is_terminal());
    let result = match cli.command {
        Command::Check(args) => {
            reporter.format = args.message_format;
            if args.stdin {
                check_stdin(&args, &mut reporter)
            } else {
                Settings::resolve(&args.common, None)
                    .and_then(|projects| check(&projects, &args, &mut reporter))
            }
        }
        Command::Fmt(args) if args.stdin => fmt_stdin(&args),
        Command::Fmt(args) => Settings::resolve(&args.common, args.indent)
            .map(|projects| fmt(&projects, args.check, &mut reporter)),
        // The fragments are compiled too: the game needs them.
        Command::Build(mut args) => {
            args.common.include_fragments = true;
            reporter.format = args.message_format;
            Settings::resolve(&args.common, None)
                .and_then(|projects| build::build(&projects, &args, &mut reporter))
        }
        Command::Init(args) => init(&args),
        Command::Lints => {
            lints();
            Ok(true)
        }
        Command::Explain { lint } => explain(&lint),
        Command::Disassemble { file } => disassemble(&file),
        Command::Lsp => papyrus_lsp::run().map(|()| true).map_err(|e| e.to_string()),
    };
    if result.is_ok() {
        reporter.finish();
    }
    match result {
        Ok(true) => ExitCode::SUCCESS,
        Ok(false) => ExitCode::FAILURE,
        Err(error) => {
            eprintln!("error: {error}");
            ExitCode::from(2)
        }
    }
}

fn lints() {
    for lint in LINTS {
        let level = lint.default.as_str();
        println!(
            "{}  {:<18} {:<6} {}",
            lint.code, lint.name, level, lint.description
        );
    }
}

fn explain(key: &str) -> Result<bool, String> {
    if key.eq_ignore_ascii_case("baseline") {
        println!("{}", baseline::HELP);
        return Ok(true);
    }
    let lint = papyrus_lint::find(key).ok_or_else(|| papyrus_lint::unknown_message(key))?;
    println!(
        "{} {} — {} by default\n\n{}\n\n{}\n\n\
         To change its level, in papyrus.toml:\n    [lints]\n    \"{name}\" = \"allow\"\n\
         To allow one case, at the end of the line or alone above it:\n    \
         ; papyrus: allow({name})",
        lint.code,
        lint.name,
        lint.default.as_str(),
        lint.description,
        papyrus_lint::explanation(lint),
        name = lint.name,
    );
    Ok(true)
}

fn disassemble(file: &Path) -> Result<bool, String> {
    let error = |e: &dyn std::fmt::Display| format!("{}: {e}", file.display());
    let bytes = std::fs::read(file).map_err(|e| error(&e))?;
    let pex = papyrus_pex::Pex::read(&bytes).map_err(|e| error(&e))?;
    std::io::stdout()
        .write_all(papyrus_pex::disassemble(&pex).as_bytes())
        .map_err(|e| e.to_string())?;
    Ok(true)
}

/// Writes a papyrus.toml for the scripts under the folder.
fn init(args: &InitArgs) -> Result<bool, String> {
    let dir = args.path.clone().unwrap_or_else(|| PathBuf::from("."));
    if !dir.is_dir() {
        return Err(format!("{}: not a folder", dir.display()));
    }
    let path = dir.join(papyrus_project::config::FILE_NAME);
    if path.exists() {
        return Err(format!("{}: already exists", path.display()));
    }
    let scripts = papyrus_project::discover(
        std::slice::from_ref(&dir),
        DiscoverOptions {
            include_fragments: false,
        },
    )
    .map_err(|e| e.to_string())?;
    let several = papyrus_project::ppj::in_folder(&dir).len();
    let ppj = match &args.ppj {
        Some(ppj) => Some(ppj.to_string_lossy().into_owned()),
        None if several > 1 => {
            return Err(format!(
                "{}: {several} `.ppj` files: choose one with `--ppj`",
                dir.display()
            ));
        }
        None => papyrus_project::edit::sole_ppj(&dir),
    };
    let base = ppj
        .as_ref()
        .map(|ppj| papyrus_project::ppj::read(&dir.join(ppj)).map_err(|e| e.to_string()))
        .transpose()?;
    let game = args
        .game
        .or(base.as_ref().and_then(|base| base.game))
        .or_else(|| detect(&scripts, None));
    std::fs::write(&path, papyrus_project::edit::template(game, ppj.as_deref()))
        .map_err(|e| format!("{}: {e}", path.display()))?;
    if let Some(base) = base {
        eprintln!("reading {}", ppj.unwrap_or_default());
        for note in &base.notes {
            eprintln!("note: {note}");
        }
        if !base.ignored.is_empty() {
            eprintln!(
                "note: left to Pyro, never run here: {}",
                base.ignored.join(", ")
            );
        }
    }
    eprintln!(
        "created {}, for {} script(s) — `papyrus check` runs on them",
        path.display(),
        scripts.len()
    );
    Ok(true)
}

/// Reads a file, or reports why it cannot.
fn read(path: &Path, reporter: &mut Reporter) -> Option<Vec<u8>> {
    match std::fs::read(path) {
        Ok(bytes) => Some(bytes),
        Err(error) => {
            reporter.io_error(path, &error);
            None
        }
    }
}

/// A project as `papyrus check` sees it: what its scripts declare, and its
/// semantic model.
struct Index {
    workspace: Workspace,
    db: Database,
    project: papyrus_hir::Project,
    files: HashMap<PathBuf, SourceFile>,
}

impl Index {
    /// The model's file of `path`, kept at `text`.
    fn file(&mut self, path: &Path, text: &str) -> Option<SourceFile> {
        let file = *self.files.get(path)?;
        if file.text(&self.db) != text {
            file.set_text(&mut self.db).to(text.to_owned());
        }
        Some(file)
    }
}

/// The tree and the lint diagnostics of a file.
fn analyze(
    decoded: &Decoded,
    settings: &Settings,
    index: &Index,
    file: Option<SourceFile>,
) -> (Parse, Vec<papyrus_lint::Diagnostic>) {
    let parse = papyrus_syntax::parse(&decoded.text, settings.dialect());
    let root = parse.syntax();
    let context = papyrus_lint::Context {
        decoded,
        root: &root,
        game: settings.game,
        flags: &settings.flags,
        workspace: &index.workspace,
        model: file.map(|file| Model {
            semantics: Semantics::new(&index.db, index.project),
            file,
        }),
    };
    let lints = papyrus_lint::run(&context, &settings.levels);
    (parse, lints)
}

/// Reads a project's scripts, then its imported ones: what they declare, to
/// follow `extends` from one file to another, and the semantic model.
/// `stdin` is a script read elsewhere than from its path.
fn index(settings: &Settings, stdin: Option<(&Path, &str)>) -> Index {
    let mut workspace = Workspace::default();
    let mut db = Database::default();
    let mut files = HashMap::new();
    let (mut own, mut imports) = (Vec::new(), Vec::new());
    let dialect = settings.dialect();
    for (path, imported) in settings
        .scripts
        .iter()
        .map(|p| (p, false))
        .chain(settings.imported.iter().map(|p| (p, true)))
    {
        let text = match stdin {
            Some((stdin, text)) if stdin == path => text.to_owned(),
            _ => {
                let Ok(bytes) = std::fs::read(path) else {
                    continue;
                };
                decode(&bytes).text
            }
        };
        let parse = papyrus_syntax::parse(&text, dialect);
        if let Some(summary) = ScriptSummary::of(&parse.syntax()) {
            // The project's own script wins over an imported one.
            if !imported || workspace.get(&summary.name).is_none() {
                workspace.insert(summary);
            }
        }
        let file = SourceFile::new(&db, path.clone(), text);
        files.insert(path.clone(), file);
        if imported { &mut imports } else { &mut own }.push(file);
    }
    let project = papyrus_hir::Project::new(&db, own, imports, settings.game);
    project.set_skse(&mut db).to(settings.config.skse);
    Index {
        workspace,
        db,
        project,
        files,
    }
}

/// Which fixes to apply.
#[derive(Debug, Clone, Copy)]
struct Fixes {
    safe: bool,
    risky: bool,
}

fn check(projects: &[Settings], args: &CheckArgs, reporter: &mut Reporter) -> Result<bool, String> {
    let (mut fixed, mut renamed) = (0, 0);
    let fixes = Fixes {
        safe: args.fix,
        risky: args.fix && args.unsafe_fixes,
    };
    let (mut hidden, mut gone) = (0, 0);
    let mut recorded = std::collections::BTreeMap::<String, usize>::new();
    for settings in projects {
        let mut baseline = (!args.no_baseline)
            .then(|| Baseline::load(&settings.root, args.write_baseline))
            .transpose()?;
        // A project only sees its own scripts, and those it imports.
        let mut index = index(settings, None);
        if fixes.risky {
            for path in &settings.scripts {
                renamed += rename_to_convention(path, settings, &mut index, reporter);
            }
        }
        for path in &settings.scripts {
            let Some(bytes) = read(path, reporter) else {
                continue;
            };
            fixed += usize::from(check_bytes(
                path,
                &bytes,
                settings,
                &mut index,
                fixes,
                baseline.as_mut(),
                reporter,
            ));
        }
        let Some(baseline) = baseline else {
            continue;
        };
        hidden += baseline.hidden;
        gone += baseline.gone();
        if args.write_baseline {
            for (code, count) in baseline.save()? {
                *recorded.entry(code).or_default() += count;
            }
        }
    }

    if args.fix {
        eprintln!("{fixed} file(s) fixed, {renamed} name(s) renamed");
    }
    let files = projects.iter().map(|p| p.scripts.len()).sum();
    reporter.summary(files, "checked");
    if args.write_baseline {
        report_recorded(&recorded);
    } else {
        report_baseline(hidden, gone);
    }
    reporter.hint();
    Ok(reporter.is_clean())
}

/// What `--write-baseline` recorded, and what to do with it.
fn report_recorded(recorded: &std::collections::BTreeMap<String, usize>) {
    let total: usize = recorded.values().sum();
    eprintln!("{total} problem(s) recorded in {}:", baseline::FILE_NAME);
    for (code, count) in recorded {
        let name = papyrus_lint::find(code).map_or("", |lint| lint.name);
        eprintln!("{count:>6}  {code} {name}");
    }
    eprintln!(
        "`papyrus check` now only reports new problems: commit the file.\n\
         `papyrus explain <code>` says what each one means, `papyrus explain baseline` how to \
         pay them down."
    );
}

/// What the baseline changed in this run.
fn report_baseline(hidden: usize, gone: usize) {
    if hidden > 0 {
        eprintln!(
            "{hidden} known problem(s) hidden by {} — `papyrus check --no-baseline` shows them",
            baseline::FILE_NAME
        );
    }
    if gone > 0 {
        eprintln!(
            "{gone} problem(s) of the baseline are gone — `papyrus check --write-baseline` \
             removes them"
        );
    }
}

fn check_stdin(args: &CheckArgs, reporter: &mut Reporter) -> Result<bool, String> {
    let bytes = read_stdin()?;
    let text = decode(&bytes).text;
    let path = stdin_path(args.stdin_filename.as_deref(), &text);
    let settings = Settings::around(&path, &args.common)?;
    let mut index = index(&settings, Some((&path, &text)));
    let mut baseline = (!args.no_baseline)
        .then(|| Baseline::load(&settings.root, false))
        .transpose()?;
    let fixes = Fixes {
        safe: false,
        risky: false,
    };
    check_bytes(
        &path,
        &bytes,
        &settings,
        &mut index,
        fixes,
        baseline.as_mut(),
        reporter,
    );
    reporter.summary(1, "checked");
    if let Some(baseline) = baseline {
        report_baseline(baseline.hidden, 0);
    }
    reporter.hint();
    Ok(reporter.is_clean())
}

/// Renames the names of a file that break the convention beyond case, across
/// the project; the number of renames. A name is left alone if the new one is
/// already in the file, or if the rename is refused, as for an event.
fn rename_to_convention(
    path: &Path,
    settings: &Settings,
    index: &mut Index,
    reporter: &mut Reporter,
) -> usize {
    let mut renamed = 0;
    let mut refused: Vec<String> = Vec::new();
    loop {
        let Some(bytes) = read(path, reporter) else {
            return renamed;
        };
        let decoded = decode(&bytes);
        let file = index.file(path, &decoded.text);
        let (parse, lints) = analyze(&decoded, settings, index, file);
        let Some(file) = file.filter(|_| parse.ok() && !decoded.lossy) else {
            return renamed;
        };
        let tokens = papyrus_syntax::lex(&decoded.text);
        let next = lints.iter().find_map(|lint| {
            let name = decoded
                .text
                .get(std::ops::Range::<usize>::from(lint.range))?;
            let new = papyrus_lint::conventional_name(lint, name)?;
            let free = !tokens
                .iter()
                .any(|t| t.text(&decoded.text).eq_ignore_ascii_case(&new));
            (free && !refused.iter().any(|r| r == name)).then(|| (lint.range, name.to_owned(), new))
        });
        let Some((range, name, new)) = next else {
            return renamed;
        };
        let edit = Semantics::new(&index.db, index.project).rename(file, range.start(), &new);
        match edit.map(|edit| apply_rename(&edit, index, reporter)) {
            Ok(true) => renamed += 1,
            _ => refused.push(name),
        }
    }
}

/// Writes a rename to its files; false if one of them cannot take it, and
/// then none is written.
fn apply_rename(
    edit: &papyrus_hir::RenameEdit,
    index: &mut Index,
    reporter: &mut Reporter,
) -> bool {
    let mut by_file: HashMap<PathBuf, Vec<papyrus_syntax::TextRange>> = HashMap::new();
    for reference in &edit.edits {
        let path = reference.file.path(&index.db).to_owned();
        by_file.entry(path).or_default().push(reference.range);
    }
    let mut writes = Vec::new();
    for (path, mut ranges) in by_file {
        let Some(bytes) = read(&path, reporter) else {
            return false;
        };
        let decoded = decode(&bytes);
        if decoded.lossy {
            return false;
        }
        let mut text = decoded.text;
        ranges.sort_by_key(|range| std::cmp::Reverse(range.start()));
        ranges.dedup();
        for range in ranges {
            text.replace_range(std::ops::Range::<usize>::from(range), &edit.new_name);
        }
        let Some(bytes) = encode(&text, decoded.encoding) else {
            return false;
        };
        writes.push((path, text, bytes));
    }
    for (path, text, bytes) in writes {
        if let Err(error) = write_atomic(&path, &bytes) {
            reporter.io_error(&path, &error);
            return false;
        }
        index.file(&path, &text);
    }
    true
}

/// Checks one file, and fixes it if asked; true if it was rewritten.
fn check_bytes(
    path: &Path,
    bytes: &[u8],
    settings: &Settings,
    index: &mut Index,
    fixes: Fixes,
    baseline: Option<&mut Baseline>,
    reporter: &mut Reporter,
) -> bool {
    let mut decoded = decode(bytes);
    let file = index.file(path, &decoded.text);
    let (mut parse, mut lints) = analyze(&decoded, settings, index, file);

    // Never on an incomplete tree, nor on a badly decoded file.
    let mut fixed = false;
    let fixable = lints
        .iter()
        .any(|d| d.fix.is_some() || (fixes.risky && d.unsafe_fix.is_some()));
    if fixes.safe && fixable && parse.ok() && !decoded.lossy {
        let result = apply_fixes_with(&decoded.text, &lints, fixes.risky)
            .and_then(|text| encode(&text, decoded.encoding).map(|bytes| (text, bytes)));
        match result {
            Some((text, bytes)) => {
                if let Err(error) = write_atomic(path, &bytes) {
                    reporter.io_error(path, &error);
                    return false;
                }
                fixed = true;
                decoded.text = text;
                let file = index.file(path, &decoded.text);
                (parse, lints) = analyze(&decoded, settings, index, file);
            }
            None => reporter.skip(path, "fix refused — please report this bug"),
        }
    }

    // Removing one thing may leave another useless: an assignment, then the
    // variable it was the only use of.
    while fixes.safe && parse.ok() && !decoded.lossy {
        let Some(text) = papyrus_lint::apply_cleanups(&decoded.text, &lints) else {
            break;
        };
        if !papyrus_syntax::parse(&text, settings.dialect()).ok() {
            reporter.skip(path, "cleanup refused — please report this bug");
            break;
        }
        let Some(bytes) = encode(&text, decoded.encoding) else {
            break;
        };
        if let Err(error) = write_atomic(path, &bytes) {
            reporter.io_error(path, &error);
            return false;
        }
        fixed = true;
        decoded.text = text;
        let file = index.file(path, &decoded.text);
        (parse, lints) = analyze(&decoded, settings, index, file);
    }

    let mut diagnostics: Vec<Diagnostic> = parse
        .errors()
        .iter()
        .map(|e| Diagnostic {
            severity: Severity::Error,
            code: "syntax".to_owned(),
            message: e.message().to_owned(),
            range: e.range(),
        })
        .collect();
    diagnostics.extend(lints.into_iter().map(|d| {
        let hint = if d.fix.is_some() || papyrus_lint::has_cleanup(&d) {
            " Fixable with `papyrus check --fix`."
        } else if d.unsafe_fix.is_some() {
            " Fixable with `papyrus check --fix --unsafe`."
        } else {
            ""
        };
        Diagnostic {
            severity: if d.level == Level::Error {
                Severity::Error
            } else {
                Severity::Warning
            },
            code: format!("{} {}", d.lint.code, d.lint.name),
            message: if hint.is_empty() || d.message.ends_with('.') {
                format!("{}{hint}", d.message)
            } else {
                format!("{}.{hint}", d.message)
            },
            range: d.range,
        }
    }));
    if let Some(baseline) = baseline {
        diagnostics = baseline.pass(path, diagnostics);
    }
    reporter.emit(path, &decoded.text, &diagnostics);
    fixed
}

fn fmt(projects: &[Settings], check_only: bool, reporter: &mut Reporter) -> bool {
    let mut changed = 0;
    for settings in projects {
        let options = FormatOptions {
            indent: settings.indent,
            keywords: keywords_of(&settings.config),
        };
        for path in &settings.scripts {
            changed += usize::from(fmt_file(
                path,
                settings.dialect(),
                &options,
                check_only,
                reporter,
            ));
        }
    }

    let verb = if check_only {
        "to reformat"
    } else {
        "reformatted"
    };
    let files: usize = projects.iter().map(|p| p.scripts.len()).sum();
    eprintln!("{changed} file(s) {verb} out of {files}");
    reporter.is_clean() && !(check_only && changed > 0)
}

/// Formats standard input on standard output, nothing on failure: an editor
/// keeps its text. With `--check`, only says if it would change.
fn fmt_stdin(args: &FmtArgs) -> Result<bool, String> {
    let bytes = read_stdin()?;
    let decoded = decode(&bytes);
    if decoded.lossy {
        return Err("invalid bytes for its encoding; rewriting it would lose them".to_owned());
    }
    let path = stdin_path(args.stdin_filename.as_deref(), &decoded.text);
    let config = Config::discover(&path).map_err(|e| e.to_string())?;
    let game = args.common.game.or(config.game).or_else(|| {
        let parse = papyrus_syntax::parse(&decoded.text, Dialect::new(GameId::Starfield));
        let verdict = papyrus_project::detect::evidence(&parse.syntax()).verdict();
        papyrus_project::detect::majority([verdict]).map(|(game, _, _)| game)
    });
    let options = FormatOptions {
        indent: indent_of(args.indent, &config),
        keywords: keywords_of(&config),
    };
    let dialect = game.map(Dialect::new).unwrap_or_default();
    let formatted =
        papyrus_fmt::format(&decoded.text, dialect, &options).map_err(|error| match error {
            FormatError::Syntax(errors) => {
                format!("{} syntax error(s), see `papyrus check`", errors.len())
            }
            error @ FormatError::Unsafe { .. } => format!("{error} — please report this bug"),
        })?;
    if args.check {
        return Ok(formatted == decoded.text);
    }
    // Re-encoded as read, like a file.
    let bytes = encode(&formatted, decoded.encoding)
        .ok_or("the result cannot be represented in the original encoding")?;
    std::io::stdout()
        .write_all(&bytes)
        .map_err(|e| format!("standard output: {e}"))?;
    Ok(true)
}

/// Formats one file; true if it changed, or would change with `--check`.
fn fmt_file(
    path: &Path,
    dialect: Dialect,
    options: &FormatOptions,
    check_only: bool,
    reporter: &mut Reporter,
) -> bool {
    let Some(bytes) = read(path, reporter) else {
        return false;
    };
    let decoded = decode(&bytes);
    if decoded.lossy {
        reporter.skip(
            path,
            "invalid bytes for its encoding; rewriting it would lose them",
        );
        return false;
    }

    let formatted = match papyrus_fmt::format(&decoded.text, dialect, options) {
        Ok(formatted) => formatted,
        Err(FormatError::Syntax(errors)) => {
            reporter.skip(
                path,
                &format!("{} syntax error(s), see `papyrus check`", errors.len()),
            );
            return false;
        }
        Err(error @ FormatError::Unsafe { .. }) => {
            reporter.skip(path, &format!("{error} — please report this bug"));
            return false;
        }
    };
    if formatted == decoded.text {
        return false;
    }

    if check_only {
        println!("{}", path.display());
        return true;
    }
    // Re-encoded as read: the formatter never changes the encoding.
    let Some(bytes) = encode(&formatted, decoded.encoding) else {
        reporter.skip(
            path,
            "the result cannot be represented in the original encoding",
        );
        return false;
    };
    if let Err(error) = write_atomic(path, &bytes) {
        reporter.io_error(path, &error);
    }
    true
}

/// Writes next to the file, then renames: an interruption never leaves a
/// half-written script.
fn write_atomic(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    let mut tmp = path.as_os_str().to_owned();
    tmp.push(".papyrus.tmp");
    let tmp = PathBuf::from(tmp);
    std::fs::write(&tmp, bytes)?;
    std::fs::rename(&tmp, path).inspect_err(|_| {
        let _ = std::fs::remove_file(&tmp);
    })
}

