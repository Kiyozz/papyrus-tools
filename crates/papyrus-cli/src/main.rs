//! `papyrus`: check and format Papyrus scripts.
//!
//! ```sh
//! papyrus check --game skyrim Source/Scripts
//! papyrus check --fix .
//! papyrus fmt --check .
//! papyrus build
//! papyrus init
//! papyrus explain PAP015
//! papyrus lsp
//! ```

