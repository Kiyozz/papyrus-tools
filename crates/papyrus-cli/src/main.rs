use report::{Diagnostic, Reporter, Severity};

#[derive(Debug, Parser)]
#[command(
    name = "papyrus",
    version,
    about = "Check, format and build Papyrus scripts"
)]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Debug, Subcommand)]
enum Command {
    /// Report syntax errors and lint findings.
    Check(CheckArgs),
    /// Format scripts in place.
    Fmt(FmtArgs),
    /// Compile scripts with the Creation Kit's compiler or Caprica, and
    /// report their errors.
    Build(BuildArgs),
    /// List the lints, their code and default level.
    Lints,
    /// Run the language server on standard input and output, for an
    /// editor.
    Lsp,
}

#[derive(Debug, Args)]
struct Common {
    /// Files or folders to process. Defaults to the current folder.
    paths: Vec<PathBuf>,

    /// Target game: skyrim, fallout4, fallout76, starfield (or sse, fo4, sf…).
    /// Overrides `game` in papyrus.toml.
    ///
    /// Without a target, the widest syntax is accepted, and encoding checks
    /// are skipped: their advice depends on the game.
    #[arg(long, short)]
    game: Option<GameId>,

    /// Include the fragments generated by the Creation Kit.
    #[arg(long)]
    include_fragments: bool,
}

#[derive(Debug, Args)]
struct CheckArgs {
    #[command(flatten)]
    common: Common,

    /// Apply safe fixes in place.
    #[arg(long)]
    fix: bool,

    /// With `--fix`, also apply unsafe fixes: the case of properties, which
    /// plugins (.esp, .esm) bind by name.
    #[arg(long = "unsafe", requires = "fix")]
    unsafe_fixes: bool,
}

#[derive(Debug, Args)]
struct FmtArgs {
    #[command(flatten)]
    common: Common,

    /// Write nothing; list the files to reformat and fail if there are any.
    #[arg(long)]
    check: bool,

    /// Indentation: a number of spaces, or `tab`. Two spaces by default, or
    /// `fmt.indent` from papyrus.toml.
    #[arg(long)]
    indent: Option<IndentArg>,
}

#[derive(Debug, Args)]
struct BuildArgs {
    #[command(flatten)]
    common: Common,

    /// The compiler: `PapyrusCompiler.exe`, or Caprica. Overrides
    /// `build.compiler` in papyrus.toml; without either, the Creation Kit's
    /// of a default Steam installation.
    #[arg(long)]
    compiler: Option<PathBuf>,

    /// Where the `.pex` files go. Overrides `build.output`; `Scripts` next
    /// to papyrus.toml by default.
    #[arg(long, short)]
    output: Option<PathBuf>,

    /// Optimize the bytecode.
    #[arg(long)]
    optimize: bool,

    /// Strip `DebugOnly` code (Fallout 4 onwards).
    #[arg(long)]
    release: bool,

    /// Strip `BetaOnly` code (Fallout 4 onwards).
    #[arg(long = "final")]
    final_: bool,
}

#[derive(Debug, Clone, Copy)]
struct IndentArg(Indent);

impl FromStr for IndentArg {
    type Err = String;

    fn from_str(s: &str) -> Result<IndentArg, String> {
        if s.eq_ignore_ascii_case("tab") || s.eq_ignore_ascii_case("tabs") {
            return Ok(IndentArg(Indent::Tabs));
        }
        match s.parse::<u8>() {
            Ok(n @ 1..=8) => Ok(IndentArg(Indent::Spaces(n))),
            _ => Err(format!(
                "`{s}`: expected a number of spaces from 1 to 8, or `tab`"
            )),
        }
    }
}

/// The settings of one project: command line, then its papyrus.toml, then
/// the defaults.
#[derive(Debug)]
struct Settings {
    /// The folder of its papyrus.toml, or the root it was found under.
    root: PathBuf,
    /// Its papyrus.toml.
    config: Config,
    scripts: Vec<PathBuf>,
    /// The scripts of the `imports` folders: read, never checked.
    imported: Vec<PathBuf>,
    game: Option<GameId>,
    indent: Indent,
    flags: Vec<FlagDef>,
    levels: Levels,
}

impl Settings {
    fn dialect(&self) -> Dialect {
        self.game.map(Dialect::new).unwrap_or_default()
    }

    /// The settings of every project under the given paths: each script
    /// follows the papyrus.toml that covers it.
    fn resolve(common: &Common, indent: Option<IndentArg>) -> Result<Vec<Settings>, String> {
        let roots = if common.paths.is_empty() {
            vec![PathBuf::from(".")]
        } else {
            common.paths.clone()
        };
        let projects = papyrus_project::projects(&roots, common.include_fragments)
            .map_err(|e| e.to_string())?;
        let several = projects.len() > 1;
        projects
            .into_iter()
            .map(|project| Settings::of(project, common, indent, several))
            .collect()
    }

    fn of(
        project: Project,
        common: &Common,
        indent: Option<IndentArg>,
        several: bool,
    ) -> Result<Settings, String> {
        let config = &project.config;
        let in_config = |message: String| match &config.path {
            Some(path) => format!("{}: {message}", path.display()),
            None => message,
        };
        // With several projects, every message says which one it is about.
        let label = several.then(|| project.root.display().to_string());

        let game = common
            .game
            .or(config.game)
            .or_else(|| detect(&project.scripts, label.as_deref()));
        let flags = match &config.flags {
            Some(path) => {
                let text = std::fs::read_to_string(path)
                    .map_err(|e| format!("{}: {e}", path.display()))?;
                parse_flags(&text).map_err(|e| format!("{}: {e}", path.display()))?
            }
            None => vanilla_flags(game),
        };
        let levels = Levels::from_config(&config.lints).map_err(in_config)?;
        let indent = match (indent, config.indent) {
            (Some(IndentArg(indent)), _) => indent,
            (None, Some(IndentSetting::Spaces(n))) => Indent::Spaces(n),
            (None, Some(IndentSetting::Tab)) => Indent::Tabs,
            (None, None) => Indent::default(),
        };
        Ok(Settings {
            root: project.root,
            config: project.config,
            scripts: project.scripts,
            imported: project.imported,
            game,
            indent,
            flags,
            levels,
        })
    }
}

/// Guesses the game of a project's scripts when neither `--game` nor its
/// papyrus.toml says it: the majority of the files that give it away.
///
/// Without any clue, `None`: the widest syntax applies, and game-dependent
/// lints stay quiet rather than guess.
fn detect(scripts: &[PathBuf], project: Option<&str>) -> Option<GameId> {
    let widest = Dialect::new(GameId::Starfield);
    let verdicts = scripts.iter().filter_map(|path| {
        let bytes = std::fs::read(path).ok()?;
        let parse = papyrus_syntax::parse(&decode(&bytes).text, widest);
        Some(papyrus_project::detect::evidence(&parse.syntax()).verdict())
    });
    let prefix = project.map(|p| format!("{p}: ")).unwrap_or_default();
    match papyrus_project::detect::majority(verdicts) {
        Some((game, votes, decided)) => {
            eprintln!(
                "{prefix}inferred target: {} ({votes} of {decided} file(s) point to it) — \
                 set `--game` or `game` in papyrus.toml to force it",
                game.display_name()
            );
            Some(game)
        }
        None => {
            eprintln!(
                "{prefix}unknown target: Starfield syntax, game-specific checks skipped — \
                 set `--game` or `game` in papyrus.toml"
            );
            None
        }
    }
}

fn main() -> ExitCode {
    let cli = Cli::parse();
    let mut reporter = Reporter::new(std::io::stderr().is_terminal());
    let result = match cli.command {
        Command::Check(args) => Settings::resolve(&args.common, None)
            .map(|projects| check(&projects, args.fix, args.unsafe_fixes, &mut reporter)),
        Command::Fmt(args) => Settings::resolve(&args.common, args.indent)
            .map(|projects| fmt(&projects, args.check, &mut reporter)),
        // The fragments are compiled too: the game needs them.
        Command::Build(mut args) => {
            args.common.include_fragments = true;
            Settings::resolve(&args.common, None)
                .and_then(|projects| build::build(&projects, &args, &mut reporter))
        }
        Command::Lints => {
            lints();
            Ok(true)
        }
        Command::Lsp => papyrus_lsp::run().map(|()| true).map_err(|e| e.to_string()),
    };
    match result {
        Ok(true) => ExitCode::SUCCESS,
        Ok(false) => ExitCode::FAILURE,
        Err(error) => {
            eprintln!("error: {error}");
            ExitCode::from(2)
        }
    }
}

fn lints() {
    for lint in LINTS {
        let level = lint.default.as_str();
        println!(
            "{}  {:<18} {:<6} {}",
            lint.code, lint.name, level, lint.description
        );
    }
}

/// Reads a file, or reports why it cannot.
fn read(path: &Path, reporter: &mut Reporter) -> Option<Vec<u8>> {
    match std::fs::read(path) {
        Ok(bytes) => Some(bytes),
        Err(error) => {
            reporter.io_error(path, &error);
            None
        }
    }
}

/// A project as `papyrus check` sees it: what its scripts declare, and its
/// semantic model.
struct Index {
    workspace: Workspace,
    db: Database,
    project: papyrus_hir::Project,
    files: HashMap<PathBuf, SourceFile>,
}

impl Index {
    /// The model's file of `path`, kept at `text`.
    fn file(&mut self, path: &Path, text: &str) -> Option<SourceFile> {
        let file = *self.files.get(path)?;
        if file.text(&self.db) != text {
            file.set_text(&mut self.db).to(text.to_owned());
        }
        Some(file)
    }
}

/// The tree and the lint diagnostics of a file.
fn analyze(
    decoded: &Decoded,
    settings: &Settings,
    index: &Index,
    file: Option<SourceFile>,
) -> (Parse, Vec<papyrus_lint::Diagnostic>) {
    let parse = papyrus_syntax::parse(&decoded.text, settings.dialect());
    let root = parse.syntax();
    let context = papyrus_lint::Context {
        decoded,
        root: &root,
        game: settings.game,
        flags: &settings.flags,
        workspace: &index.workspace,
        model: file.map(|file| Model {
            semantics: Semantics::new(&index.db, index.project),
            file,
        }),
    };
    let lints = papyrus_lint::run(&context, &settings.levels);
    (parse, lints)
}

/// Reads a project's scripts, then its imported ones: what they declare, to
/// follow `extends` from one file to another, and the semantic model.
fn index(settings: &Settings) -> Index {
    let mut workspace = Workspace::default();
    let mut db = Database::default();
    let mut files = HashMap::new();
    let (mut own, mut imports) = (Vec::new(), Vec::new());
    let dialect = settings.dialect();
    for (path, imported) in settings
        .scripts
        .iter()
        .map(|p| (p, false))
        .chain(settings.imported.iter().map(|p| (p, true)))
    {
        let Ok(bytes) = std::fs::read(path) else {
            continue;
        };
        let text = decode(&bytes).text;
        let parse = papyrus_syntax::parse(&text, dialect);
        if let Some(summary) = ScriptSummary::of(&parse.syntax()) {
            // The project's own script wins over an imported one.
            if !imported || workspace.get(&summary.name).is_none() {
                workspace.insert(summary);
            }
        }
        let file = SourceFile::new(&db, path.clone(), text);
        files.insert(path.clone(), file);
        if imported { &mut imports } else { &mut own }.push(file);
    }
    let project = papyrus_hir::Project::new(&db, own, imports, settings.game);
    project.set_skse(&mut db).to(settings.config.skse);
    Index {
        workspace,
        db,
        project,
        files,
    }
}

/// Which fixes to apply.
#[derive(Debug, Clone, Copy)]
struct Fixes {
    safe: bool,
    risky: bool,
}

fn check(projects: &[Settings], fix: bool, unsafe_fixes: bool, reporter: &mut Reporter) -> bool {
    let mut fixed = 0;
    let fixes = Fixes {
        safe: fix,
        risky: fix && unsafe_fixes,
    };
    for settings in projects {
        // A project only sees its own scripts, and those it imports.
        let mut index = index(settings);
        for path in &settings.scripts {
            fixed += usize::from(check_file(path, settings, &mut index, fixes, reporter));
        }
    }

    if fix {
        eprintln!("{fixed} file(s) fixed");
    }
    let files = projects.iter().map(|p| p.scripts.len()).sum();
    reporter.summary(files, "checked");
    reporter.is_clean()
}

/// Checks one file, and fixes it if asked; true if it was rewritten.
fn check_file(
    path: &Path,
    settings: &Settings,
    index: &mut Index,
    fixes: Fixes,
    reporter: &mut Reporter,
) -> bool {
    let Some(bytes) = read(path, reporter) else {
        return false;
    };
    let mut decoded = decode(&bytes);
    let file = index.file(path, &decoded.text);
    let (mut parse, mut lints) = analyze(&decoded, settings, index, file);

    // Never on an incomplete tree, nor on a badly decoded file.
    let mut fixed = false;
    let fixable = lints
        .iter()
        .any(|d| d.fix.is_some() || (fixes.risky && d.unsafe_fix.is_some()));
    if fixes.safe && fixable && parse.ok() && !decoded.lossy {
        let result = apply_fixes_with(&decoded.text, &lints, fixes.risky)
            .and_then(|text| encode(&text, decoded.encoding).map(|bytes| (text, bytes)));
        match result {
            Some((text, bytes)) => {
                if let Err(error) = write_atomic(path, &bytes) {
                    reporter.io_error(path, &error);
                    return false;
                }
                fixed = true;
                decoded.text = text;
                let file = index.file(path, &decoded.text);
                (parse, lints) = analyze(&decoded, settings, index, file);
            }
            None => reporter.skip(path, "fix refused — please report this bug"),
        }
    }

    let mut diagnostics: Vec<Diagnostic> = parse
        .errors()
        .iter()
        .map(|e| Diagnostic {
            severity: Severity::Error,
            code: "syntax".to_owned(),
            message: e.message().to_owned(),
            range: e.range(),
        })
        .collect();
    diagnostics.extend(lints.into_iter().map(|d| {
        let hint = if d.fix.is_some() {
            " Fixable with `papyrus check --fix`."
        } else if d.unsafe_fix.is_some() {
            " Fixable with `papyrus check --fix --unsafe`."
        } else {
            ""
        };
        Diagnostic {
            severity: if d.level == Level::Error {
                Severity::Error
            } else {
                Severity::Warning
            },
            code: format!("{} {}", d.lint.code, d.lint.name),
            message: format!("{}{hint}", d.message),
            range: d.range,
        }
    }));
    reporter.emit(path, &decoded.text, &diagnostics);
    fixed
}

fn fmt(projects: &[Settings], check_only: bool, reporter: &mut Reporter) -> bool {
    let mut changed = 0;
    for settings in projects {
        let options = FormatOptions {
            indent: settings.indent,
        };
        for path in &settings.scripts {
            changed += usize::from(fmt_file(
                path,
                settings.dialect(),
                &options,
                check_only,
                reporter,
            ));
        }
    }

    let verb = if check_only {
        "to reformat"
    } else {
        "reformatted"
    };
    let files: usize = projects.iter().map(|p| p.scripts.len()).sum();
    eprintln!("{changed} file(s) {verb} out of {files}");
    reporter.is_clean() && !(check_only && changed > 0)
}

/// Formats one file; true if it changed, or would change with `--check`.
fn fmt_file(
    path: &Path,
    dialect: Dialect,
    options: &FormatOptions,
    check_only: bool,
    reporter: &mut Reporter,
) -> bool {
    let Some(bytes) = read(path, reporter) else {
        return false;
    };
    let decoded = decode(&bytes);
    if decoded.lossy {
        reporter.skip(
            path,
            "invalid bytes for its encoding; rewriting it would lose them",
        );
        return false;
    }

    let formatted = match papyrus_fmt::format(&decoded.text, dialect, options) {
        Ok(formatted) => formatted,
        Err(FormatError::Syntax(errors)) => {
            reporter.skip(
                path,
                &format!("{} syntax error(s), see `papyrus check`", errors.len()),
            );
            return false;
        }
        Err(error @ FormatError::Unsafe { .. }) => {
            reporter.skip(path, &format!("{error} — please report this bug"));
            return false;
        }
    };
    if formatted == decoded.text {
        return false;
    }

    if check_only {
        println!("{}", path.display());
        return true;
    }
    // Re-encoded as read: the formatter never changes the encoding.
    let Some(bytes) = encode(&formatted, decoded.encoding) else {
        reporter.skip(
            path,
            "the result cannot be represented in the original encoding",
        );
        return false;
    };
    if let Err(error) = write_atomic(path, &bytes) {
        reporter.io_error(path, &error);
    }
    true
}

/// Writes next to the file, then renames: an interruption never leaves a
/// half-written script.
fn write_atomic(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    let mut tmp = path.as_os_str().to_owned();
    tmp.push(".papyrus.tmp");
    let tmp = PathBuf::from(tmp);
    std::fs::write(&tmp, bytes)?;
    std::fs::rename(&tmp, path).inspect_err(|_| {
        let _ = std::fs::remove_file(&tmp);
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_indent_reads_as_spaces_or_tabs() {
        assert_eq!("4".parse::<IndentArg>().unwrap().0, Indent::Spaces(4));
        assert_eq!("tab".parse::<IndentArg>().unwrap().0, Indent::Tabs);
        assert_eq!("TABS".parse::<IndentArg>().unwrap().0, Indent::Tabs);
        assert!("0".parse::<IndentArg>().is_err());
        assert!("deux".parse::<IndentArg>().is_err());
    }

    #[test]
    fn the_command_line_is_consistent() {
        use clap::CommandFactory;
        Cli::command().debug_assert();
    }

    #[test]
    fn game_aliases_are_accepted() {
        let cli = Cli::try_parse_from(["papyrus", "check", "--game", "sse", "x"]).unwrap();
        let Command::Check(args) = cli.command else {
            panic!("subcommand");
        };
        assert_eq!(args.common.game, Some(GameId::Skyrim));
    }
}
