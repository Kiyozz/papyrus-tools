//! Discovery of the `.psc` files to process.
//!
//! No installation lookup: only the given paths are walked.
//!
//! # Fragments
//!
//! The Creation Kit generates one script per quest, dialogue, scene or perk
//! fragment. Nobody writes them by hand, and reformatting or linting them
//! only brings noise: they are excluded by default.
//!
//! Measured on the three games, a fragment is recognized by one of two
//! signs, without false positives:
//!
//! - it lives under a `Fragments` folder (Fallout 4, Starfield);
//! - its name contains a `TIF`, `QF`, `SF`, `PF`, `PRKF` or `TERM` segment:
//!   `TIF__0010CB55`, `DLC2_PF_…_02020993`, `QF_ccBGSSSE025_DarkRevFrag`.
//!   Skyrim stores its 10,437 fragments flat, Fallout 4 leaves 394 outside
//!   the `Fragments` folders.

use std::io;
use std::path::{Path, PathBuf};

/// What discovery must include.
#[derive(Debug, Clone, Copy, Default)]
pub struct DiscoverOptions {
    /// Include the fragments generated by the Creation Kit.
    pub include_fragments: bool,
}

/// The name segments that mark a fragment.
const FRAGMENT_MARKERS: [&str; 6] = ["TIF", "QF", "SF", "PF", "PRKF", "TERM"];

/// True if `path` designates a `.psc`.
pub fn is_script(path: &Path) -> bool {
    path.extension()
        .is_some_and(|e| e.eq_ignore_ascii_case("psc"))
}

/// True if the file name is a fragment's.
pub fn is_fragment_name(path: &Path) -> bool {
    let Some(stem) = path.file_stem().and_then(|s| s.to_str()) else {
        return false;
    };
    // The last segment is never a marker: a `_` must follow.
    let mut segments: Vec<&str> = stem.split('_').collect();
    segments.pop();
    segments
        .iter()
        .any(|s| FRAGMENT_MARKERS.iter().any(|m| s.eq_ignore_ascii_case(m)))
}

fn is_fragment_dir(path: &Path) -> bool {
    path.file_name()
        .is_some_and(|n| n.eq_ignore_ascii_case("fragments"))
}

/// The `.psc` files designated by `roots`, sorted.
///
/// An explicitly given file is always kept, fragment or not: the request is
/// explicit. A folder is walked recursively.
pub fn discover(roots: &[PathBuf], options: DiscoverOptions) -> io::Result<Vec<PathBuf>> {
    let mut out = Vec::new();
    for root in roots {
        if root.is_dir() {
            walk(root, options, &mut out)?;
        } else if root.exists() {
            out.push(root.clone());
        } else {
            return Err(io::Error::new(
                io::ErrorKind::NotFound,
                format!("{} : introuvable", root.display()),
            ));
        }
    }
    out.sort();
    out.dedup();
    Ok(out)
}

fn walk(dir: &Path, options: DiscoverOptions, out: &mut Vec<PathBuf>) -> io::Result<()> {
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            if options.include_fragments || !is_fragment_dir(&path) {
                walk(&path, options, out)?;
            }
        } else if is_script(&path) && (options.include_fragments || !is_fragment_name(&path)) {
            out.push(path);
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn les_fragments_se_reconnaissent_a_leur_nom() {
        for name in [
            "TIF__0010CB55.psc",
            "QF_MQ101_0002610C.psc",
            "DLC2_PF_DLC2MQ04NelothToWorks_02020993.psc",
            "ccBGSSSE001_TIF__05000C73.psc",
            "QF_ccBGSSSE025_DarkRevFrag.psc",
            "PRKF_VRWorkshopShared_PerkOp_0100003F.psc",
            "tif__0010cb55.psc",
        ] {
            assert!(is_fragment_name(Path::new(name)), "{name}");
        }
    }

    #[test]
    fn les_scripts_ordinaires_ne_sont_pas_des_fragments() {
        for name in [
            "ObjectReference.psc",
            "SQ_ParentScript.psc",
            "SFBGS00DRandomEnableOnLoadScript.psc",
            "MyTIFHelper.psc",
            // The marker must be followed by a segment.
            "Foo_QF.psc",
            "QF.psc",
        ] {
            assert!(!is_fragment_name(Path::new(name)), "{name}");
        }
    }
}
